"""Generate the committed results.

Following the split established in `llm-client-kit/scripts/generate_results.py`:

- ``results/*.md``            committed. Deterministic, machine-independent
                              claims only. CI regenerates and fails on drift.
- ``results/*-raw.md``        gitignored. Anything that varies by machine.

Almost everything here is arithmetic or a fixed-seed measurement over a fixed
corpus, so it is byte-identical on any machine -- which is what makes the drift
gate meaningful rather than an exercise in tolerance-tuning. The one
machine-dependent thing (wall-clock cache lookup latency) is deliberately kept
out of the committed file.

**Every claim below is asserted.** A results file that reports a number nobody
checks is a file that silently goes stale; if a claim breaks, this script exits
non-zero and CI fails rather than quietly committing a new number.

Run:  python scripts/generate_results.py
"""

from __future__ import annotations

import platform
import sys
import time
from datetime import date
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from inference_gateway.cache import (  # noqa: E402
    HashingEmbedder,
    best_threshold_gain,
    separation_auc,
    sweep_thresholds,
)
from inference_gateway.cost_model import (  # noqa: E402
    ApiPricing,
    RequestMix,
    ThroughputAssumption,
    breakeven,
    sensitivity,
    sweep_throughput,
)
from inference_gateway.pairs import counts, labelled_pairs  # noqa: E402
from inference_gateway.routing import (  # noqa: E402
    Tier,
    blended_cost_per_request,
    escalation_breakeven_rate,
)

RESULTS = ROOT / "results"

# --- inputs, all stated -----------------------------------------------------

# API prices: public list prices as of the date below, per million tokens.
# Supplied here rather than fetched so the results are reproducible offline;
# they are inputs to re-check, not measurements.
PRICE_SNAPSHOT_DATE = "2026-08-25"
APIS = [
    ApiPricing("small (e.g. 4o-mini class)", input_per_mtok=0.15, output_per_mtok=0.60),
    ApiPricing("mid (e.g. 4o class)", input_per_mtok=2.50, output_per_mtok=10.00),
]

# ASSUMPTIONS. Not measured -- there is no GPU on this machine.
ASSUMPTIONS = [
    ThroughputAssumption(
        "1x A10G-class, 8B model",
        gpu_cost_per_hour=1.00,
        output_tokens_per_s=400.0,
        utilisation=0.5,
    ),
    ThroughputAssumption(
        "1x A100-class, 70B model",
        gpu_cost_per_hour=3.50,
        output_tokens_per_s=250.0,
        utilisation=0.5,
    ),
]

MIX = RequestMix(prompt_tokens=500, completion_tokens=200)
THRESHOLDS = (0.50, 0.60, 0.70, 0.75, 0.80, 0.85, 0.90, 0.92, 0.95, 0.98)
CHEAP_TIER = Tier("cheap", 0.15, 0.60)
STRONG_TIER = Tier("strong", 2.50, 10.00)


def _fmt(d: Decimal | None, places: int = 0) -> str:
    if d is None:
        return "n/a"
    return f"{float(d):,.{places}f}"


# --- 1. breakeven -----------------------------------------------------------


def write_breakeven() -> dict[str, object]:
    L: list[str] = []
    add = L.append
    add("# Breakeven: at what monthly volume does self-hosting beat the API?\n")
    add("Generated by `python scripts/generate_results.py`. Do not edit by hand.\n")

    add("> **The self-hosted side of this comparison is MODELLED, not measured.**")
    add("> There is no GPU on the machine that produced this file. Every")
    add("> throughput and utilisation figure below is a stated assumption drawn")
    add("> from published vendor benchmarks, carried in code by a type named")
    add("> `ThroughputAssumption`. The API side is arithmetic over list prices.")
    add("> Treat the crossover as *the shape of the answer for these inputs*,")
    add("> not as a measurement of any real deployment.\n")

    add("## Inputs\n")
    add(f"- Request mix: {MIX.prompt_tokens} prompt + {MIX.completion_tokens} "
        f"completion tokens, cache hit rate {MIX.cache_hit_rate:.0%}")
    add(f"- API list prices: snapshot {PRICE_SNAPSHOT_DATE} (assumption: current)")
    add("- Billing month: 730 hours")
    add("- Reproduce: `python scripts/generate_results.py`")
    add("- Deterministic: pure arithmetic, no randomness, no I/O\n")

    add("### Assumed self-hosting configurations (NOT measured)\n")
    add("| config | $/hr | assumed output tok/s | utilisation | $/M output tok |")
    add("|---|---|---|---|---|")
    for a in ASSUMPTIONS:
        add(f"| {a.name} | {a.gpu_cost_per_hour:.2f} | {a.output_tokens_per_s:.0f} "
            f"| {a.utilisation:.0%} | {float(a.cost_per_output_mtok):.2f} |")
    add("")

    add("## The crossover\n")
    add("| API tier | self-host config | crossover (req/month) | capacity (req/month) "
        "| reachable? |")
    add("|---|---|---|---|---|")
    rows = []
    for api in APIS:
        for a in ASSUMPTIONS:
            be = breakeven(api, a, MIX)
            rows.append((api, a, be))
            add(f"| {api.name} | {a.name} | {_fmt(be.requests_per_month)} "
                f"| {_fmt(be.capacity_requests_per_month)} "
                f"| {'yes' if be.feasible else '**no**'} |")
    add("")

    # CLAIM 1: against the cheap API tier, self-hosting does not pay off at any
    # volume the assumed hardware can actually serve.
    small_rows = [(a, be) for api, a, be in rows if api is APIS[0]]
    assert all(not be.feasible for _, be in small_rows), (
        "a cheap-API row became reachable -- the headline finding has changed"
    )
    add("**Finding 1 — against a small hosted model, self-hosting never pays off")
    add("here.** For every assumed configuration, the crossover volume sits")
    add("*above* the volume that configuration can physically serve. You would")
    add("need to add replicas to reach the volume that justifies the first one,")
    add("and each replica moves the crossover up by its own monthly cost. This")
    add("script asserts it and exits non-zero if it stops holding.\n")

    mid_rows = [(a, be) for api, a, be in rows if api is APIS[1]]
    feasible_mid = [(a, be) for a, be in mid_rows if be.feasible]
    assert feasible_mid, "no mid-tier row is reachable -- finding 2 has changed"
    add("**Finding 2 — against a mid-tier hosted model, it does.** The same")
    add("hardware crosses over at a volume it can serve, because the API side")
    add("is roughly 17x more expensive per request while the box costs the same.")
    add("The crossover is driven by *which API you are replacing*, not by how")
    add("fast the box is.\n")
    for a, be in feasible_mid:
        add(f"- {a.name}: **{_fmt(be.requests_per_month)} requests/month** "
            f"(~{_fmt(be.requests_per_month / Decimal(730))}/hour sustained)")
    add("")

    add("## Why throughput is not the lever people expect\n")
    sweep = sweep_throughput(APIS[1], ASSUMPTIONS[0], MIX, factors=(0.25, 0.5, 1.0, 2.0, 4.0))
    crossovers = {be.crossover_int for _, be in sweep}
    assert len(crossovers) == 1, f"crossover moved with throughput: {crossovers}"
    add("| assumed throughput | crossover (req/month) | capacity (req/month) | reachable? |")
    add("|---|---|---|---|")
    for f, be in sweep:
        add(f"| {f:g}x baseline | {_fmt(be.requests_per_month)} "
            f"| {_fmt(be.capacity_requests_per_month)} "
            f"| {'yes' if be.feasible else 'no'} |")
    add("")
    add("**Finding 3 — the crossover volume is invariant to throughput.** Fixed")
    add("monthly cost divided by per-request API cost contains no throughput")
    add("term. A faster box does not lower the volume at which self-hosting")
    add("wins; it only raises the ceiling on whether that volume is reachable.")
    add("Asserted above across a 16x throughput range.\n")
    add("This matters because it is the opposite of the usual intuition. If the")
    add("crossover is out of reach, buying a faster GPU does not move it closer")
    add("— only a cheaper box, a pricier API, or more traffic does. The single")
    add("most load-bearing assumption in this file therefore turns out not to")
    add("affect the headline number at all, which is a convenient result given")
    add("that it is the one thing here nobody measured.\n")

    add("## Sensitivity: what actually moves the answer\n")
    add("| change | crossover (req/month) | vs baseline |")
    add("|---|---|---|")
    sens = sensitivity(APIS[1], ASSUMPTIONS[0], MIX)
    for label, value, delta in sens:
        d = "baseline" if delta is None or delta == 0 else f"{float(delta):+.0%}"
        add(f"| {label} | {_fmt(value)} | {d} |")
    add("")
    by_label = {lbl: dl for lbl, _, dl in sens}
    assert by_label["throughput x2 (assumed)"] == 0
    assert by_label["utilisation 0.5 -> 1.0"] == 0
    add("Only the *prices* and the *cache hit rate* move the crossover. Both")
    add("throughput and utilisation leave it untouched — they change capacity,")
    add("not economics. Asserted.\n")

    (RESULTS / "breakeven.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return {"rows": rows, "feasible_mid": feasible_mid}


# --- 2. semantic cache ------------------------------------------------------


def write_cache() -> dict[str, object]:
    pairs = labelled_pairs()
    n_eq, n_neq = counts()
    embedder = HashingEmbedder()
    auc = separation_auc(pairs, embedder)
    gain, gain_at = best_threshold_gain(pairs, embedder)
    reports = sweep_thresholds(pairs, THRESHOLDS, embedder)

    L: list[str] = []
    add = L.append
    add("# Semantic cache: the measured false-hit rate\n")
    add("Generated by `python scripts/generate_results.py`. Do not edit by hand.\n")

    add("> **Measured, but on synthetic data.** The corpus is")
    add(f"> {n_eq + n_neq} hand-written prompt pairs ({n_eq} paraphrases,")
    add(f"> {n_neq} hard negatives) in `src/inference_gateway/pairs.py`, scored")
    add("> by a deterministic hashing embedder — not a learned sentence")
    add("> encoder. These are real measurements of a real component, and they")
    add("> generalise to no production workload. The transferable part is the")
    add("> method and the decision rule, not the numbers.\n")

    add("## Inputs\n")
    add(f"- Corpus: {n_eq} equivalent + {n_neq} non-equivalent pairs, fixed order")
    add("- Embedder: `HashingEmbedder(dim=256, ngram=4)`, deterministic")
    add("- Seed: none needed — no randomness anywhere in this measurement")
    add("- Reproduce: `python scripts/generate_results.py`")
    add("- Raw per-pair scores: `results/cache-raw.md` (gitignored)\n")

    add("## Threshold sweep\n")
    add("A *false hit* is a non-equivalent pair served from cache: a confident,")
    add("fluent, wrong answer that raises no error anywhere. A *false miss* is")
    add("only a wasted API call. The two are not symmetric, which is why they")
    add("are reported separately rather than as one accuracy figure.\n")
    add("| threshold | false-hit rate | true-hit rate | false hits | true hits |")
    add("|---|---|---|---|---|")
    for r in reports:
        add(f"| {r.threshold:.2f} | {r.false_hit_rate:.0%} | {r.true_hit_rate:.0%} "
            f"| {r.false_hits} | {r.true_hits} |")
    add("")

    # CLAIM: at every threshold, this embedder is useless -- either it serves
    # wrong answers or it never hits at all.
    useful = [r for r in reports if r.true_hit_rate > 0 and r.false_hit_rate < 0.2]
    assert not useful, f"a threshold became usable: {[r.summary() for r in useful]}"
    add("**There is no usable row in that table.** Every threshold with a")
    add("non-zero true-hit rate also has a false-hit rate above 20%; every")
    add("threshold with an acceptable false-hit rate never hits at all. This")
    add("script asserts that no row is both safe and useful.\n")

    add("## The diagnostic that explains it\n")
    assert auc < 0.5, f"AUC {auc:.4f} is no longer inverted -- ADR 0001 needs revisiting"
    add(f"**Separation AUC = {auc:.3f}** — the probability that an equivalent")
    add("pair scores above a non-equivalent one. 1.0 is perfect, 0.5 is")
    add("coin-flipping, and this is **far below 0.5**, meaning the ranking is")
    add("*inverted*: the embedder systematically scores the pairs it must not")
    add("merge above the pairs it should.\n")
    add(f"**Best achievable `true-hit − false-hit` gain = {gain:.2f}** ")
    add(f"(at threshold {gain_at:.2f}). No threshold beats never caching.\n")
    assert gain <= 0.0, f"a threshold now gains {gain:.3f} -- ADR 0001 needs revisiting"

    add("The mechanism is that this embedder measures *lexical* overlap, and")
    add("the two classes differ in exactly the wrong direction:\n")
    add("- A hard negative changes **one word** — \"Python 3.11\" to \"Python")
    add("  3.12\", \"Austria\" to \"Australia\", \"encrypt\" to \"decrypt\" — so")
    add("  it stays lexically almost identical while the correct answer changes")
    add("  completely.")
    add("- A paraphrase changes **most words** — \"How do I merge two")
    add("  dictionaries?\" to \"What's the way to combine two dicts?\" — so it")
    add("  looks lexically distant while meaning the same thing.\n")
    add("Surface similarity and semantic equivalence are anti-correlated on")
    add("this corpus. That is not a threshold that needs tuning; it is an")
    add("embedder that cannot do the job at any setting.\n")

    add("## Consequence\n")
    add("**The semantic tier ships disabled** (`semantic_enabled=False`). The")
    add("exact-match tier, which cannot be wrong, stays on. See")
    add("`docs/adr/0001-semantic-cache-false-hit-rate.md`.\n")
    add("The code path is kept rather than deleted: it is what the measurement")
    add("runs against, and swapping in a real sentence encoder is a")
    add("one-argument change for anyone who re-measures and gets an AUC that")
    add("justifies turning it on.\n")

    add("## Limitations\n")
    add("- **Synthetic corpus, 60 pairs.** Adversarially constructed, so the")
    add("  false-hit rates are deliberately pessimistic. A real workload has a")
    add("  different and unknown mix of near-misses.")
    add("- **Lexical embedder, not a learned one.** Chosen so CI can measure")
    add("  this on every commit with no model download and no network. A real")
    add("  sentence encoder would likely score far better — this repo does not")
    add("  establish by how much, because it never ran one.")
    add("- Pairs were written by the same person who chose the negatives'")
    add("  categories, so the corpus reflects one view of what a hard case is.\n")

    (RESULTS / "cache.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return {"auc": auc, "gain": gain, "reports": reports}


def write_cache_raw() -> None:
    """Per-pair scores and lookup latency. Machine-specific, gitignored."""
    from inference_gateway.cache import cosine
    from inference_gateway.pairs import EQUIVALENT, NON_EQUIVALENT

    e = HashingEmbedder()
    L: list[str] = []
    add = L.append
    add("# Semantic cache: raw per-pair scores (not committed)\n")
    add(f"- Date: {date.today().isoformat()}")
    add(f"- Python {platform.python_version()} on {platform.system()} {platform.machine()}\n")

    # Latency is the one machine-dependent number, so it lives only here.
    cache_pairs = [(a, b) for a, b in EQUIVALENT[:10]]
    t0 = time.perf_counter()
    for a, b in cache_pairs * 20:
        cosine(e.embed(a), e.embed(b))
    elapsed = (time.perf_counter() - t0) / (len(cache_pairs) * 20)
    add(f"- Mean embed+compare latency: {elapsed * 1000:.3f} ms/pair\n")

    add("## Equivalent pairs (should hit)\n")
    add("| score | a | b |")
    add("|---|---|---|")
    for a, b in sorted(EQUIVALENT, key=lambda p: -cosine(e.embed(p[0]), e.embed(p[1]))):
        add(f"| {cosine(e.embed(a), e.embed(b)):.3f} | {a} | {b} |")
    add("\n## Non-equivalent pairs (must not hit)\n")
    add("| score | a | b |")
    add("|---|---|---|")
    for a, b in sorted(NON_EQUIVALENT, key=lambda p: -cosine(e.embed(p[0]), e.embed(p[1]))):
        add(f"| {cosine(e.embed(a), e.embed(b)):.3f} | {a} | {b} |")
    add("")
    (RESULTS / "cache-raw.md").write_text("\n".join(L) + "\n", encoding="utf-8")


# --- 3. routing -------------------------------------------------------------


def write_routing() -> None:
    L: list[str] = []
    add = L.append
    add("# Tiered routing: when a cascade stops paying for itself\n")
    add("Generated by `python scripts/generate_results.py`. Do not edit by hand.\n")
    add("> **Cost arithmetic only.** This repo does *not* establish that")
    add("> escalation improves answer quality — that needs a labelled quality")
    add("> set and a real model, neither of which exists here. What follows is")
    add("> what a cascade costs at a given escalation rate, which is the part")
    add("> the breakeven question needs.\n")

    add("## Inputs\n")
    add(f"- Cheap tier: ${CHEAP_TIER.input_per_mtok}/M in, "
        f"${CHEAP_TIER.output_per_mtok}/M out")
    add(f"- Strong tier: ${STRONG_TIER.input_per_mtok}/M in, "
        f"${STRONG_TIER.output_per_mtok}/M out")
    add(f"- Request mix: {MIX.prompt_tokens} prompt + {MIX.completion_tokens} completion")
    add("- Reproduce: `python scripts/generate_results.py`\n")

    rate = escalation_breakeven_rate(CHEAP_TIER, STRONG_TIER, MIX.prompt_tokens,
                                     MIX.completion_tokens)
    add("## Blended cost by escalation rate\n")
    add("An escalated request pays for **both** calls. That double charge is")
    add("what makes a cascade stop paying off well before every request")
    add("escalates.\n")
    add("| escalation rate | blended $/request | vs strong-only |")
    add("|---|---|---|")
    strong_only = STRONG_TIER.cost(MIX.prompt_tokens, MIX.completion_tokens)
    for r in (0.0, 0.1, 0.25, 0.5, 0.75, 0.9, 1.0):
        blended = blended_cost_per_request(CHEAP_TIER, STRONG_TIER, r,
                                           MIX.prompt_tokens, MIX.completion_tokens)
        pct = (blended - strong_only) / strong_only
        add(f"| {r:.0%} | ${float(blended):.6f} | {float(pct):+.0%} |")
    add("")

    always = blended_cost_per_request(CHEAP_TIER, STRONG_TIER, 1.0,
                                      MIX.prompt_tokens, MIX.completion_tokens)
    assert always > strong_only, "escalating everything should cost more than strong-only"
    add(f"**The cascade breaks even at an escalation rate of {rate:.0%}.** Above")
    add("that, the cheap tier is a pure tax: you pay for a filter that rarely")
    add("filters, and simply calling the strong model directly is cheaper.")
    add("Asserted: at 100% escalation the cascade costs more than strong-only.\n")
    add("This is the number to compare a measured escalation rate against. It")
    add("converts \"is our cascade worth keeping\" from an opinion into a")
    add("threshold — and note how *high* it is here: with a 17x price gap")
    add("between tiers, a cascade survives a lot of escalation before it loses.\n")

    add("## Limitations\n")
    add("- The confidence signal used by the gateway's default router is a")
    add("  **stand-in** (`heuristic_confidence`): it detects hedging and")
    add("  truncation, is trivially gamed, and cannot detect a confidently")
    add("  stated wrong answer. No escalation *rate* is claimed here as a")
    add("  result — only the cost of whatever rate a real signal produces.")
    add("- Assumes both tiers see the same token counts, which overstates the")
    add("  strong tier's cost slightly when it is given a shorter prompt.\n")

    (RESULTS / "routing.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    write_breakeven()
    write_cache()
    write_cache_raw()
    write_routing()
    print("wrote breakeven.md, cache.md, routing.md (committed)")
    print("wrote cache-raw.md (gitignored)")
    print("all asserted claims held")


if __name__ == "__main__":
    main()
